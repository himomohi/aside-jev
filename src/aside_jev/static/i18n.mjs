export const messages = { en: Object.fromEntries(Object.keys(ko).map((key) => [key, key])), ko };
export function createI18n(storageKey, storage) {
  if (storage === undefined) { try { storage = globalThis.localStorage; } catch { storage = null; } }
  let language = "en";
  try { if (storage?.getItem(storageKey) === "ko") language = "ko"; } catch { /* 저장이 차단되어도 영어 기본 화면은 동작한다. */ }
  const api = {
    get language() { return language; },
    get locale() { return language === "ko" ? "ko-KR" : "en-US"; },
    t(key, values = {}) {
      const pattern = messages[language][key] ?? messages.en[key] ?? key;
      return pattern.replace(/\{(\w+)\}/g, (match, name) => Object.hasOwn(values, name) ? String(values[name]) : match);
    },
    setLanguage(next, { persist = true } = {}) {
      language = next === "ko" ? "ko" : "en";
      try { if (persist) storage?.setItem(storageKey, language); } catch { /* 현재 화면에서는 저장 없이 적용한다. */ }
      return language;
    },
    apply(root = document) {
      root.documentElement.lang = language;
      root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = api.t(el.dataset.i18n); });
      for (const attribute of ["aria-label", "placeholder", "title"]) {
        root.querySelectorAll(`[data-i18n-${attribute}]`).forEach((el) => el.setAttribute(attribute, api.t(el.getAttribute(`data-i18n-${attribute}`))));
      }
    },
    validate(form) {
      for (const field of form.elements) {
        if (!field.setCustomValidity || !field.willValidate) continue;
        field.setCustomValidity("");
        if (field.validity.valueMissing) field.setCustomValidity(api.t("Please fill out this field."));
        else if (field.validity.rangeOverflow || field.validity.rangeUnderflow) field.setCustomValidity(api.t("Enter a value between {min} and {max}.", { min: field.min, max: field.max }));
        else if (!field.validity.valid) field.setCustomValidity(api.t("Enter a valid value."));
      }
      return form.reportValidity();
    },
  };
  return api;
}
